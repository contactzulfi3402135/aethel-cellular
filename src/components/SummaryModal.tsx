import { useEscape, useLockBody } from '../lib/hooks';
import type { EngineResult } from '../lib/age';

export interface SummaryData {
  age: number;
  labels: { sleep: string; rhr: string; vo2: string; glucose: string };
  result: EngineResult;
  accession: string;
}

function Meta({ k, v }: { k: string; v: string }) {
  return (
    <div>
      <p className="font-mono text-[9px] uppercase tracking-[0.18em] text-slate2/70">{k}</p>
      <p className="mt-1.5 font-mono text-[11px] leading-relaxed text-pine">{v}</p>
    </div>
  );
}

function Row({ k, v, accent }: { k: string; v: string; accent?: boolean }) {
  return (
    <div className="flex items-baseline justify-between gap-6 px-4 py-3">
      <dt className="font-mono text-[10px] uppercase tracking-[0.14em] text-slate2">{k}</dt>
      <dd className={`text-right font-mono text-[12px] tabular-nums ${accent ? 'text-emerald2' : 'text-pine'}`}>{v}</dd>
    </div>
  );
}

export default function SummaryModal({ data, onClose }: { data: SummaryData; onClose: () => void }) {
  useLockBody(true);
  useEscape(true, onClose);
  const { result } = data;
  const today = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' });
  const reversal = result.optimized
    ? 'Within optimized band — maintenance pathway'
    : `−${result.reversal.toFixed(1)} yrs over 18 months`;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
      <div className="absolute inset-0 bg-pine/70 backdrop-blur-[3px]" onClick={onClose} />
      <div className="relative flex max-h-[90vh] w-full max-w-xl flex-col overflow-hidden border border-hairline bg-canvas">
        <div className="flex items-center justify-between border-b border-hairline bg-pine px-6 py-4">
          <div>
            <p className="font-mono text-[9px] uppercase tracking-[0.26em] text-bone/50">
              Confidential &middot; Aethel Epigenetic Engine
            </p>
            <p className="mt-1 font-serif text-lg text-canvas">Clinical Health Summary</p>
          </div>
          <div className="flex items-center gap-4">
            <p className="font-mono text-[10px] tracking-[0.08em] text-bone/70">{data.accession}</p>
            <button type="button" onClick={onClose} aria-label="Close summary" className="text-bone/60 transition-colors hover:text-bone">
              <svg width="14" height="14" viewBox="0 0 14 14" stroke="currentColor" strokeWidth="1.2">
                <path d="M1 1l12 12M13 1L1 13" />
              </svg>
            </button>
          </div>
        </div>
        <div className="overflow-y-auto px-6 py-7 sm:px-8">
          <div className="grid grid-cols-1 gap-4 border-b border-hairline pb-5 sm:grid-cols-3">
            <Meta k="Generated" v={today} />
            <Meta k="Subject" v="Prospective Patient — Unregistered" />
            <Meta k="Model" v="AE-P4 · v4.2 · 09/2026" />
          </div>

          <h4 className="mt-6 font-mono text-[10px] uppercase tracking-[0.26em] text-slate2">Input Parameters</h4>
          <dl className="mt-3 divide-y divide-hairline border border-hairline">
            <Row k="Chronological Age" v={`${data.age} yrs`} />
            <Row k="Average Nightly Deep Sleep" v={data.labels.sleep} />
            <Row k="Resting Heart Rate" v={data.labels.rhr} />
            <Row k="VO2 Max Tier" v={data.labels.vo2} />
            <Row k="Metabolic Status" v={data.labels.glucose} />
          </dl>

          <h4 className="mt-7 font-mono text-[10px] uppercase tracking-[0.26em] text-slate2">Computed Output</h4>
          <dl className="mt-3 divide-y divide-hairline border border-hairline">
            <Row k="Projected DNAm PhenoAge" v={`${result.phenoAge.toFixed(1)} yrs (chronological ${data.age})`} />
            <Row
              k="Delta vs Chronological"
              v={`${result.delta >= 0 ? '+' : '−'}${Math.abs(result.delta).toFixed(1)} yrs`}
            />
            <Row k="Rate of Aging Factor" v={`${result.factor.toFixed(2)}x (population baseline 1.00x)`} />
            <Row k="Reversal Potential" v={reversal} accent />
          </dl>

          <p className="mt-6 text-[11.5px] leading-relaxed text-slate2">
            This summary reflects the AE-P4 calibrated projection from your declared physiological parameters. Formal
            interpretation is issued by your physician of record following a supervised baseline draw.
          </p>
          <p className="mt-4 border-t border-hairline pt-4 font-mono text-[9px] uppercase tracking-[0.16em] text-slate2/70">
            Generated by the Aethel Epigenetic Diagnostic Engine &middot; Zürich / London / Geneva
          </p>
        </div>
      </div>
    </div>
  );
}
